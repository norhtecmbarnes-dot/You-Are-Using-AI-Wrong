#!/usr/bin/env python3
"""Generate control/references/the-rules.md from RULES.md.

WHY THIS EXISTS. On 12 October 2026 the shipped reference copy of the rules was found to be
six rules stale: RULES.md had grown to 28 entries and the reference still held 22. Nobody
had noticed, because nothing compared them. It was the same defect the book spends its time
on - one fact, several copies, nothing authoritative, and the outdated copy retrieved as
readily as the current one.

So the reference is GENERATED, not maintained. Rule 6 of the book this file carries says it
plainly: put your rules in code and config, where they persist, never in a habit. Re-run this
after any edit to RULES.md.

    python3 book-build/make-rules-reference.py

It writes only the file below, and it refuses to write if RULES.md looks wrong (no rules
found, or the author-facing placement note leaked through), so a broken source cannot
silently produce a broken reference.
"""

import os
import re
import sys

B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(B, "RULES.md")
DST = os.path.join(B, "control", "references", "the-rules.md")

HEADER = """# The Rules

*From* You Are Using AI Wrong - And It Isn't Your Fault *by Michael C. Barnes. Content CC BY-SA 4.0.*

**How to read this list.** Each rule has three parts:

- **The assumption** - what you believed before you picked up the book. Not stupid, and not your fault.
- **What's actually true** - the correction, in one line.
- **The rule** - what to do instead, today.

None of these require you to give up AI. Every one of them makes it work better.

**Two ways in.** Read this page and you can act today - every rule ends in something you can do.
Read the book and you will know *why* each one is true. The page is the lobby; the book is the
argument. If you sign the cheques, your rules are **2, 13, 14, 16 and 17** - start there. If you
make projects work, your rules are **1, 2, 5, 9, 11b and 14b**. If you have not built yet, read
Part I first; it is the warning.

---

"""

FOOTER = """
---

*Generated from `RULES.md` by `book-build/make-rules-reference.py`. **Do not edit this file** - edit
`RULES.md` and re-run the script. A reference that is maintained by hand drifts from its source; this
one cannot.*
"""

# Author-facing material that must never reach the reader.
DROP_SECTIONS = [
    re.compile(r"(?m)^##\s+Placement note.*\Z", re.S),
]


def main():
    try:
        src = open(SRC, encoding="utf-8").read()
    except OSError as e:
        sys.exit("cannot read %s: %s" % (SRC, e))

    body = src
    for pat in DROP_SECTIONS:
        body = pat.sub("", body)

    # Drop the front matter of RULES.md - the reference carries its own header.
    body = re.sub(r"(?s)\A.*?(?=^## Part )", "", body, flags=re.M)

    # ASCII-clean, matching the shipped reference's convention.
    body = body.replace("\u2014", "-").replace("\u2013", "-")
    body = re.sub(r"[ \t]+\n", "\n", body).strip() + "\n"

    n = len(re.findall(r"(?m)^\*\*\d+[a-z]?\.", body))
    if n < 20:
        sys.exit("refusing to write: only %d rules found in %s - the source looks wrong" % (n, SRC))
    if "Placement note" in body or "not part of the rules" in body:
        sys.exit("refusing to write: author-facing material leaked through")

    out = HEADER + body + FOOTER
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)

    print("wrote %s" % DST)
    print("   rules: %d" % n)
    print("   words: %d" % len(re.findall(r"[A-Za-z][A-Za-z'-]*", out)))


if __name__ == "__main__":
    main()
